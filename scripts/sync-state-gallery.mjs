/**
 * Sync state gallery images from states.zip layout into public/images/states/
 * and regenerate src/data/states/stateGalleryImages.ts
 *
 * Usage: node scripts/sync-state-gallery.mjs [path-to-states-folder-or-zip]
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const PUBLIC_DIR = path.join(ROOT, 'public', 'images', 'states');
const OUT_FILE = path.join(ROOT, 'src', 'data', 'states', 'stateGalleryImages.ts');

const FOLDER_TO_SLUG = {
  bihar: 'bihar',
  delhi: 'delhi',
  karnataka: 'karnataka',
  kerala: 'kerala',
  'madya pradesh': 'madhya-pradesh',
  maharastra: 'maharashtra',
  tamilnadu: 'tamil-nadu',
  telangana: 'telangana',
  uttarakhand: 'uttarakhand',
  'west bengol': 'west-bengal',
};

const SLUG_NAMES = {
  bihar: 'Bihar',
  delhi: 'Delhi',
  karnataka: 'Karnataka',
  kerala: 'Kerala',
  'madhya-pradesh': 'Madhya Pradesh',
  maharashtra: 'Maharashtra',
  'tamil-nadu': 'Tamil Nadu',
  telangana: 'Telangana',
  uttarakhand: 'Uttarakhand',
  'west-bengal': 'West Bengal',
};

const CATEGORIES = ['workshops', 'schools', 'communities', 'volunteers', 'awareness'];
const SKIP_EXT = new Set(['.heic', '.mov', '.mp4']);

function sanitizeName(base) {
  const safe = base.replace(/[^a-zA-Z0-9._-]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '').toLowerCase();
  return safe || 'photo';
}

function scanPublicGalleries() {
  const manifest = {};
  if (!fs.existsSync(PUBLIC_DIR)) return manifest;

  for (const slug of fs.readdirSync(PUBLIC_DIR)) {
    const dir = path.join(PUBLIC_DIR, slug);
    if (!fs.statSync(dir).isDirectory()) continue;
    const files = fs
      .readdirSync(dir)
      .filter(f => !SKIP_EXT.has(path.extname(f).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    manifest[slug] = files.map(f => `/images/states/${slug}/${f}`);
  }
  return manifest;
}

function copyFromSource(statesRoot) {
  fs.mkdirSync(PUBLIC_DIR, { recursive: true });

  for (const folder of fs.readdirSync(statesRoot)) {
    const folderPath = path.join(statesRoot, folder);
    if (!fs.statSync(folderPath).isDirectory()) continue;
    const slug = FOLDER_TO_SLUG[folder];
    if (!slug) {
      console.warn(`Skip unmapped folder: ${folder}`);
      continue;
    }

    const destDir = path.join(PUBLIC_DIR, slug);
    fs.mkdirSync(destDir, { recursive: true });

    const files = fs.readdirSync(folderPath).sort();
    let i = 0;
    for (const file of files) {
      const ext = path.extname(file).toLowerCase();
      if (SKIP_EXT.has(ext)) continue;
      i += 1;
      const outName = `${sanitizeName(path.basename(file, path.extname(file)))}${ext}`;
      fs.copyFileSync(path.join(folderPath, file), path.join(destDir, outName));
    }
    console.log(`${slug}: copied ${i} images`);
  }
}

function generateTs(manifest) {
  const slugs = Object.keys(manifest).filter(s => manifest[s].length > 0).sort();
  const blocks = slugs.map(slug => {
    const name = SLUG_NAMES[slug] ?? slug;
    const items = manifest[slug].map((src, i) => {
      const cat = CATEGORIES[i % CATEGORIES.length];
      const id = `${slug}-g${i + 1}`;
      const alt = `Saukhyam ${cat} programme in ${name}`;
      return `    { id: '${id}', src: '${src}', alt: '${alt}', category: '${cat}' as const },`;
    });
    return `  '${slug}': [\n${items.join('\n')}\n  ],`;
  });

  const content = `import type { GalleryItem } from './experienceData';

/* Auto-generated by scripts/sync-state-gallery.mjs — do not hand-edit paths */

export const STATE_GALLERY_BY_SLUG: Record<string, GalleryItem[]> = {
${blocks.join('\n')}
};

export function getStateGallery(slug: string, stateName: string): GalleryItem[] | undefined {
  const items = STATE_GALLERY_BY_SLUG[slug];
  if (!items?.length) return undefined;
  return items.map(item => ({
    ...item,
    alt: item.alt.replace(/ in [^']+$/, \` in \${stateName}\`),
  }));
}

export function getStateHeroImage(slug: string): string | undefined {
  return STATE_GALLERY_BY_SLUG[slug]?.[0]?.src;
}
`;

  fs.writeFileSync(OUT_FILE, content, 'utf8');
  console.log(`Wrote ${OUT_FILE} (${slugs.length} states)`);
}

function resolveStatesRoot(input) {
  if (!input) return null;
  const resolved = path.resolve(input);
  if (!fs.existsSync(resolved)) throw new Error(`Not found: ${resolved}`);
  if (resolved.toLowerCase().endsWith('.zip')) {
    const tmp = path.join(path.dirname(resolved), 'states-extracted-sync');
    fs.mkdirSync(tmp, { recursive: true });
    execSync(
      `powershell -NoProfile -Command "Expand-Archive -Path '${resolved.replace(/'/g, "''")}' -DestinationPath '${tmp.replace(/'/g, "''")}' -Force"`,
      { stdio: 'inherit' },
    );
    const nested = path.join(tmp, 'states');
    return fs.existsSync(nested) ? nested : tmp;
  }
  if (fs.existsSync(path.join(resolved, 'states'))) return path.join(resolved, 'states');
  return resolved;
}

const input = process.argv[2] ?? 'C:/Users/Shiva/Downloads/states.zip';
const statesRoot = resolveStatesRoot(input);
if (statesRoot) copyFromSource(statesRoot);
generateTs(scanPublicGalleries());
